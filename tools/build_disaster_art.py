"""Export and verify RIP disaster strips. Python 3.10+, Pillow 11.3.

python -B tools/build_disaster_art.py [--check]
Vanilla donors are copied byte-for-byte. Generated strips are only resized.
"""
from pathlib import Path
import argparse
import json
import re
import shutil
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'gfx/interface/disasters'
SOURCE = ART / 'source'
MANIFEST = json.loads((SOURCE / 'manifest.json').read_text(encoding='utf-8'))
GFX = ROOT / 'interface/rip_disasters.gfx'


def sprite_text() -> str:
    lines = ['# Generated by tools/build_disaster_art.py; edit source/manifest.json.',
             'spriteTypes = {']
    for name in MANIFEST:
        lines.extend(['\tspriteType = {', f'\t\tname = "GFX_disaster_{name}"',
                      f'\t\ttexturefile = "gfx//interface//disasters//rip_{name}.dds"',
                      '\t\tnoOfFrames = 3', '\t\tloadType = "INGAME"', '\t}'])
    return '\n'.join(lines + ['}', ''])


def master(name: str) -> Image.Image:
    with Image.open(SOURCE / MANIFEST[name]['source']) as im:
        if im.width != im.height * 3:
            raise ValueError(f'{name}: expected a 3:1 source strip, got {im.size}')
        # Resize each state separately: no filtering across frame boundaries.
        out = Image.new('RGBA', (132, 44))
        for frame in range(3):
            tile = im.crop((frame * im.height, 0, (frame + 1) * im.height, im.height))
            tile = tile.convert('RGBA').resize((44, 44), Image.Resampling.LANCZOS)
            out.paste(tile, (frame * 44, 0))
        return out


def build() -> None:
    for name, entry in MANIFEST.items():
        target = ART / f'rip_{name}.dds'
        if entry['kind'] == 'vanilla':
            raw = (SOURCE / entry['source']).read_bytes()
            if not target.exists() or target.read_bytes() != raw:
                shutil.copyfile(SOURCE / entry['source'], target)
        else:
            desired = master(name)
            if target.exists():
                with Image.open(target) as current:
                    if current.size == desired.size and current.convert('RGBA').tobytes() == desired.tobytes():
                        continue
            desired.save(target, format='DDS')
    GFX.write_text(sprite_text(), encoding='utf-8', newline='\n')


def check() -> None:
    assert GFX.read_text(encoding='utf-8') == sprite_text(), 'Regenerate rip_disasters.gfx'
    for name, entry in MANIFEST.items():
        target = ART / f'rip_{name}.dds'
        if entry['kind'] == 'vanilla':
            assert target.read_bytes() == (SOURCE / entry['source']).read_bytes(), name
        else:
            with Image.open(target) as im:
                assert im.convert('RGBA').tobytes() == master(name).tobytes(), name
    disasters = set()
    for path in (ROOT / 'common/disasters').glob('*.txt'):
        disasters.update(re.findall(r'(?m)^(\w+)\s*=\s*\{', path.read_text(encoding='utf-8-sig')))
    sprites = {}
    for path in (ROOT / 'interface').glob('*.gfx'):
        text = re.sub(r'(?m)#.*$', '', path.read_text(encoding='utf-8-sig'))
        for block in re.findall(r'spriteType\s*=\s*\{([^{}]*)\}', text):
            match = re.search(r'\bname\s*=\s*"GFX_disaster_(\w+)"', block)
            if match:
                sprites.setdefault(match[1], []).append(block)
    for name in sorted(disasters):
        assert len(sprites.get(name, [])) == 1, (name, 'missing/duplicate sprite')
        block = sprites[name][0]
        assert re.search(r'noOfFrames\s*=\s*3\b', block), name
        path = re.search(r'texturefile\s*=\s*"([^"]+)"', block).group(1)
        target = ROOT / path.replace('//', '/')
        raw = target.read_bytes()
        assert raw[:4] == b'DDS ' and len(raw) == 23360, name
        assert raw[84:88] == b'\0' * 4, (name, 'expected uncompressed DDS')
        with Image.open(target) as im:
            assert im.size == (132, 44), (name, im.size)
            frames = [im.crop((44*i, 0, 44*(i+1), 44)).tobytes() for i in range(3)]
            assert len(set(frames)) == 3, (name, 'repeated states')
        print('PASS:', name, 'unique sprite; DDS 132x44; three distinct states')
    assert set(MANIFEST) <= disasters, 'Manifest contains nonexistent disasters'
    print(f'DISASTER ART PASS: {len(disasters)}/{len(disasters)} covered')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if not args.check:
        build()
    check()
