"""Build EU4 1.37 idea-file overrides while keeping RIP's individual sets editable."""
import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FILES = {
    "00_country_ideas.txt": ("KIE_ideas",),
    "zz_group_ideas.txt": ("ruthenian_ideas", "cossack_ideas"),
}


def build(vanilla, filename, groups):
    raw = (vanilla / "common/ideas" / filename).read_bytes()
    try:
        source = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        source = raw.decode("cp1252")
    source = source.replace("\r\n", "\n")
    for group in groups:
        # Vanilla closes these top-level groups at column zero.
        pattern = rf"^{group}\s*=\s*\{{[^\n]*\n.*?^\}}[ \t]*$"
        source, count = re.subn(pattern, f"# {group} is defined in RIP's separate idea file.",
                                source, flags=re.M | re.S)
        if count != 1:
            raise ValueError(f"{filename}: expected one {group}, found {count}")
    lines = [line.rstrip() for line in source.splitlines()]
    return "# Generated by tools/build_kyiv_idea_overrides.py for EU4 1.37.5.\n" + "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("vanilla", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for filename, groups in FILES.items():
        target = ROOT / "common/ideas" / filename
        result = build(args.vanilla, filename, groups)
        if args.check:
            if target.read_text(encoding="utf-8") != result:
                raise SystemExit(f"Stale override: {filename}")
        else:
            target.write_text(result, encoding="utf-8", newline="\n")
